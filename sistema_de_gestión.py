from abc import ABC, abstractmethod
import logging

# ==========================================
# CONFIGURACIÓN DE LOGS
# ==========================================
logging.basicConfig(
    filename="logs.txt",
    level=logging.ERROR,
    format="%(asctime)s - %(levelname)s - %(message)s"
)

# ==========================================
# EXCEPCIONES PERSONALIZADAS
# ==========================================
class ClienteError(Exception): pass
class ServicioError(Exception): pass
class ReservaError(Exception): pass

# ==========================================
# CLASE ABSTRACTA
# ==========================================
class Entidad(ABC):
    @abstractmethod
    def mostrar_info(self): pass

# ==========================================
# CLIENTE
# ==========================================
class Cliente(Entidad):
    def __init__(self, nombre, email):
        if not nombre:
            raise ClienteError("Nombre vacío")
        if "@" not in email:
            raise ClienteError("Email inválido")
        self.__nombre = nombre
        self.__email = email

    def mostrar_info(self):
        return f"Cliente: {self.__nombre} - {self.__email}"

    def get_nombre(self): return self.__nombre

# ==========================================
# SERVICIOS
# ==========================================
class Servicio(Entidad, ABC):
    def __init__(self, nombre, costo_base):
        self.nombre = nombre
        self.costo_base = costo_base

    @abstractmethod
    def calcular_costo(self, duracion): pass

class ServicioSala(Servicio):
    def calcular_costo(self, horas): return self.costo_base * horas
    def mostrar_info(self): return f"Sala: {self.nombre} - {self.costo_base}"

class ServicioEquipo(Servicio):
    def calcular_costo(self, dias): return self.costo_base * dias
    def mostrar_info(self): return f"Equipo: {self.nombre} - {self.costo_base}"

class ServicioAsesoria(Servicio):
    def calcular_costo(self, horas, descuento=0):
        return (self.costo_base * horas) - descuento
    def mostrar_info(self): return f"Asesoría: {self.nombre} - {self.costo_base}"

# ==========================================
# RESERVA
# ==========================================
class Reserva:
    def __init__(self, cliente, servicio, duracion):
        if not isinstance(cliente, Cliente):
            raise ReservaError("Cliente inválido")
        if not isinstance(servicio, Servicio):
            raise ReservaError("Servicio inválido")
        if duracion <= 0:
            raise ReservaError("Duración inválida")

        self.cliente = cliente
        self.servicio = servicio
        self.duracion = duracion
        self.estado = "Pendiente"

    def confirmar(self): self.estado = "Confirmada"
    def cancelar(self): self.estado = "Cancelada"

    def procesar(self):
        try:
            costo = self.servicio.calcular_costo(self.duracion)
            self.confirmar()
            return costo
        except Exception as e:
            logging.error(e)
            self.cancelar()

