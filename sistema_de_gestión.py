        try:
            if opcion == "1":
                nombre = input("Nombre: ")
                email = input("Email: ")
                cliente = Cliente(nombre, email)
                clientes.append(cliente)
                print("Cliente creado")

            elif opcion == "2":
                for c in clientes:
                    print(c.mostrar_info())

            elif opcion == "3":
                if not clientes or not servicios:
                    raise ReservaError("No hay datos")
                cliente = clientes[0]
                servicio = servicios[0]
                reserva = Reserva(cliente, servicio, 2)
                reservas.append(reserva)
                print("Reserva creada")

            elif opcion == "4":
                for r in reservas:
                    print(f"{r.cliente.get_nombre()} - {r.estado}")

            elif opcion == "5":
                break

        except Exception as e:
            logging.error(e)
            print("Error controlado")

